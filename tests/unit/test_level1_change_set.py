"""The level-1 change set has to survive the product's own gate, offline.

On the stand the scripted runner applies the change set, runs ``make setup`` and
commits with the product's ``.githooks`` armed. A change set that any of those
refuse costs a stand run to find out. This module applies the same change set to
the vendored render of the pinned kit and runs, right here, the product's own
gate over the result — with the *kit's own tooling*, at the same commit the
fixture resolves.

What is executed here, not described
------------------------------------

* the *runner's own parser and applier* — ``noop._SCRIPT`` is executed, not
  reimplemented, so the format this suite emits is judged by the code that will
  read it;
* ``make setup``'s own steps over the applied tree: ``python -m
  framework.generate``, then the kit's ``ruff format`` and ``ruff check --fix``;
* every check of the kit's ``make lint`` that the product's ``pre-push`` runs
  when Docker is unavailable — and the worker images carry no Docker, so that is
  the path the stand takes: ``ruff format --check``, ``ruff check``, ``xenon``,
  ``framework.spec.loader.validate_specs_cli``,
  ``framework.enforce_spec_compliance``,
  ``framework.lint.controller_sync.lint_controllers_cli`` and ``deptry`` for
  every service the change set touches (``make check-deps``);
* the generated settings registry the deployed endpoint reads back, produced by
  the real generator rather than asserted from the manifest alone.

``codegen-kit-tooling`` is a test-only dependency of this repository, pinned at
exactly the commit the fixture's own ``pyproject.toml`` resolves;
:func:`test_the_kit_tooling_is_pinned_to_the_commit_the_fixture_resolves` fails
if the two ever drift.

What it deliberately does not claim
-----------------------------------

Two checks of the product's gate need the *product's per-service virtualenvs*,
which do not exist in this tree and cannot be built offline:

* ``framework.lint.package_imports`` takes ``--site-packages`` from
  ``services/backend/.venv/bin/python``, so it has nothing to point at here;
* the kit's ``make tests <svc>`` runs ``services/<svc>/.venv/bin/pytest``.
  Materialising those environments means resolving and building the product's
  own dependency trees (``asyncpg``, ``psycopg``, ``faststream``,
  ``python-telegram-bot``) from the network inside a unit test, which would make
  this suite neither offline nor hermetic. They stay the stand's job — the
  scripted runner's ``push`` step runs them through ``pre-push``, and a failure
  there now names the step (see ``record_engineering_failure_steps``).

The ruff, xenon and deptry binaries are this repository's rather than the
product's pinned ones. The pristine fixture is therefore put through the same
gate in the same run, so a tool release that starts flagging the kit fails as a
baseline rather than as a defect of the change set.
"""

