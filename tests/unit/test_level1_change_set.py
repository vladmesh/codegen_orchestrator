def test_the_kit_tooling_is_pinned_to_the_commit_the_fixture_resolves() -> None:
    """The gate is only honest while it runs the tooling the stand runs.

    The fixture's `pyproject.toml` is what the rendered product resolves
    `codegen-kit-tooling` from; this repository depends on the same commit so the
    checks below are the product's own. A pin moved on one side alone fails here.
    """
    ours = tomllib.loads((REPO_ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    source = ours["tool"]["uv"]["sources"]["codegen-kit-tooling"]
    fixture = (TEMPLATE_PIN.fixture_path() / "pyproject.toml").read_text(encoding="utf-8")

    assert "codegen-kit-tooling" in ours["dependency-groups"]["dev"]
    assert f"codegen-product-kit.git@{source['rev']}" in fixture


