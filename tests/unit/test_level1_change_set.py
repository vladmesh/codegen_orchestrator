def test_the_generated_registry_carries_the_product_setting(setup_tree: Path, change_sets) -> None:
    """The real generator, not the manifest, is asked what the deployment will read.

    The deployed endpoint reports `SETTINGS_SCHEMAS`, so what the live probe
    asserts — exactly one key ending in the setting's name, whose declared
    default is this run's marker — is checked here against the generator's own
    output.
    """
    module, sets = change_sets
    registry = _load(
        "level1_settings_schemas",
        setup_tree / "services/backend/src/generated/settings_schemas.py",
    )

    declaring = {
        key: schema
        for key, schema in registry.SETTINGS_SCHEMAS.items()
        if schema.get("default") == sets.marker
    }
    assert list(declaring) == [module.LEVEL1_SETTING_KEY]
    assert registry.SETTINGS_SCHEMA_SOURCES[module.LEVEL1_SETTING_KEY] == "backend"


