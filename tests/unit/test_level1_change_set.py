def _load(name: str, path: Path) -> ModuleType:
    spec = importlib.util.spec_from_file_location(name, path)
    assert spec and spec.loader, path
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


#: Variables that would let a checker see *this* repository while it judges the
#: product tree. `PYTHONPATH` is the load-bearing one: the offline sweep runs
#: pytest with the orchestrator root on it, which makes `services` and `shared`
#: importable — and deptry then reclassifies the product's own `services.*`
#: imports as a transitive dependency and reports 40 DEP003 violations that the
#: stand, where nothing but the product is importable, never sees. A checker
#: pointed at the product must see only the product.
FOREIGN_ENVIRONMENT = ("PYTHONPATH", "VIRTUAL_ENV")


def _product_environment(**overrides: str) -> dict[str, str]:
    environment = {
        key: value for key, value in os.environ.items() if key not in FOREIGN_ENVIRONMENT
    }
    environment.update(overrides)
    return environment


def _tool(
    tree: Path, name: str, *args: str, cwd: Path | None = None
) -> subprocess.CompletedProcess:
    executable = shutil.which(name)
    assert executable, f"{name} is not on PATH; run this suite through `uv run`"
    return subprocess.run(  # noqa: S603
        [executable, *args],
        cwd=cwd or tree,
        env=_product_environment(),
        capture_output=True,
        text=True,
        check=False,
    )


def _kit(tree: Path, *args: str) -> subprocess.CompletedProcess:
    """Run one of the kit's own tooling entry points against ``tree``.

    ``framework.lib.env.get_repo_root`` honours ``SERVICE_TEMPLATE_ROOT``, which
    is how the product's tooling is pointed at a checkout that is not the
    current repository.
    """
    return subprocess.run(  # noqa: S603
        [sys.executable, *args],
        cwd=tree,
        env=_product_environment(SERVICE_TEMPLATE_ROOT=str(tree), PYTHONPATH=str(tree)),
        capture_output=True,
        text=True,
        check=False,
    )


def _ruff(tree: Path, *args: str) -> subprocess.CompletedProcess:
    return _tool(tree, "ruff", *args)


def _ruff_format_check(tree: Path) -> subprocess.CompletedProcess:
    return _ruff(tree, "format", "--check", "--exclude", FORMAT_EXCLUDE, ".")


def _ruff_diagnostics(tree: Path) -> list[dict]:
    result = _ruff(tree, "check", "--output-format", "json", ".")
    assert result.stdout, result.stderr
    return json.loads(result.stdout)


def _product_gate(tree: Path) -> dict[str, subprocess.CompletedProcess]:
    """Every step of the kit's `make lint` this tree can answer for, by name.

    Keyed by step so a failure says which check of the product's gate refused,
    the same way the stand's evidence now names the runner step that failed.
    """
    results = {
        "ruff format --check": _ruff_format_check(tree),
        "ruff check": _ruff(tree, "check", "."),
        "xenon": _tool(tree, "xenon", *XENON_ARGS, "."),
        "validate-specs": _kit(tree, "-c", VALIDATE_SPECS),
        "enforce-spec-compliance": _kit(tree, "-m", "framework.enforce_spec_compliance"),
        "lint-controllers": _kit(tree, "-c", LINT_CONTROLLERS),
    }
    for service in DEPTRY_SERVICES:
        results[f"check-deps {service}"] = _tool(
            tree, "deptry", "src/", cwd=tree / "services" / service
        )
    return results


def _assert_gate_passes(results: dict[str, subprocess.CompletedProcess]) -> None:
    failed = {
        step: (result.stdout + result.stderr).strip()
        for step, result in results.items()
        if result.returncode != 0
    }

    assert failed == {}


def _make_setup(tree: Path) -> None:
    """The kit's own `make setup`, minus the `uv sync` steps this tree has no venvs for.

    Order matters and is the Makefile's: the generator writes first, then ruff
    formats and fixes what it wrote. Asserting the gate against a tree the
    generator never touched would be asserting against something the stand never
    has.
    """
    generated = _kit(tree, "-m", "framework.generate")
    assert generated.returncode == 0, generated.stdout + generated.stderr
    formatted = _ruff(tree, "format", "--extend-exclude", "*.md", ".")
    assert formatted.returncode == 0, formatted.stdout + formatted.stderr
    fixed = _ruff(tree, "check", "--fix", ".")
    assert fixed.returncode == 0, fixed.stdout + fixed.stderr


