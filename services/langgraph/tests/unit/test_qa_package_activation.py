"""Central QA against a product that carries a kit package.

Three things are asserted here, and they are the three the card asks for.

* A package's scheduled behaviour reaches the run the same way a service's
  does. The name is read off the criteria, retained by criteria preparation,
  named to the executor and accepted by `fire_job` — a package prefix is a
  name, not a new mechanism, and the dispatch rule that decides a service's
  behaviour decides a package's unchanged.
* The connection check and the acceptance checks are answered from the
  deployed product: the packages this run states are the ones its own
  generated contract records on the target, cross-checked against the backend
  manifest allowlist it booted with.
* A contract that cannot be read is never "no packages". Every unreadable,
  truncated, half-present or inconsistent artifact fails the run before an
  executor starts, because a check that examined nothing must not pass.
"""

