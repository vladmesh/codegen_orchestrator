class TestTheProbeReadsTheDeployedProduct:
    """What the run may state about packages, it read off this deployment."""

    async def test_the_active_set_is_read_from_the_products_own_contract(self):
        session = _package_product()

        outcome = await run_package_activation_checks(session)

        assert outcome.failure is None
        assert outcome.activation == PackageActivation(
            packages=(REMINDERS,),
            listed=("reminders",),
            jobs={"daily_digest": "backend", "reminders.tick": "package:reminders"},
        )
        assert session.read[0] == BACKEND_MANIFEST
        assert ACTIVE_PACKAGE_CONTRACT in session.read

    async def test_a_package_free_product_is_left_exactly_as_it_was(self):
        session = FakeSession(
            {
                BACKEND_MANIFEST: MANIFEST_WITHOUT_PACKAGES,
                ACTIVE_PACKAGE_CONTRACT: PACKAGE_FREE_SOURCE,
            }
        )

        outcome = await run_package_activation_checks(session)

        assert outcome.activation is None
        assert outcome.failure is None
        # Nothing was read that a package-free run does not need: the generated
        # job registry belongs to the package path only.
        assert GENERATED_JOB_REGISTRY not in session.read

